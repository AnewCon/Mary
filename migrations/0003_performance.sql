CREATE TABLE IF NOT EXISTS exchange_bills(id TEXT PRIMARY KEY,ts INTEGER NOT NULL,ccy TEXT NOT NULL,pnl TEXT NOT NULL,fee TEXT NOT NULL,funding TEXT NOT NULL,kind TEXT NOT NULL,data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS exchange_bills_time ON exchange_bills(ts DESC,id DESC);
CREATE TABLE IF NOT EXISTS exchange_fills(id TEXT PRIMARY KEY,ts INTEGER NOT NULL,inst_id TEXT NOT NULL,data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS exchange_fills_time ON exchange_fills(ts DESC,id DESC);
CREATE TABLE IF NOT EXISTS performance_state(id INTEGER PRIMARY KEY CHECK(id=1),data TEXT NOT NULL);
